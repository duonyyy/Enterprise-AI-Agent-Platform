"""
Layer 4 Defense: AST Security Sandbox (Abstract Syntax Tree Parser).
Inspects code generated by LLMs before execution to block malicious functions and system calls.
"""

import ast
from typing import Set, Any, Dict


class ASTSecurityViolation(Exception):
    """Raised when dangerous code AST nodes are encountered."""
    pass


class ASTSecurityScanner(ast.NodeVisitor):
    FORBIDDEN_FUNCS: Set[str] = {"eval", "exec", "open", "__import__", "compile", "globals", "locals"}
    FORBIDDEN_MODULES: Set[str] = {"os", "sys", "subprocess", "socket", "shutil", "requests", "http"}

    def __init__(self):
        self.violations = []

    def visit_Import(self, node: ast.Import):
        for alias in node.names:
            if alias.name.split(".")[0] in self.FORBIDDEN_MODULES:
                self.violations.append(f"Forbidden module import: {alias.name}")
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom):
        if node.module and node.module.split(".")[0] in self.FORBIDDEN_MODULES:
            self.violations.append(f"Forbidden module from-import: {node.module}")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call):
        if isinstance(node.func, ast.Name) and node.func.id in self.FORBIDDEN_FUNCS:
            self.violations.append(f"Forbidden function call: {node.func.id}")
        elif isinstance(node.func, ast.Attribute) and node.func.attr in self.FORBIDDEN_FUNCS:
            self.violations.append(f"Forbidden attribute call: {node.func.attr}")
        self.generic_visit(node)


class ASTSecuritySandbox:
    def __init__(self):
        self.scanner = ASTSecurityScanner()

    def validate_code(self, source_code: str) -> bool:
        """Parses and audits code syntax tree."""
        try:
            tree = ast.parse(source_code)
        except SyntaxError as e:
            raise ASTSecurityViolation(f"Invalid Python syntax: {e}")

        scanner = ASTSecurityScanner()
        scanner.visit(tree)
        if scanner.violations:
            raise ASTSecurityViolation(f"Security sandbox violation: {'; '.join(scanner.violations)}")
        return True

    def execute_safe_math(self, source_code: str, scope: Dict[str, Any]) -> Any:
        """
        Validates through AST, then executes within a restricted global scope.
        Guarantees deterministic calculation for commercial penalties.
        """
        self.validate_code(source_code)
        # Sandbox execution scope with NO builtins
        safe_globals = {"__builtins__": {
            "abs": abs, "round": round, "min": min, "max": max, "sum": sum,
            "int": int, "float": float, "str": str, "bool": bool
        }}
        safe_locals = dict(scope)
        exec(source_code, safe_globals, safe_locals)
        return safe_locals

